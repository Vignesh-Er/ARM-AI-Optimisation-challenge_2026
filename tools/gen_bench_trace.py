"""Task 3.1: generate bench/bench_trace.h, the standard 2000-step/seed-42
input trace baked in as C arrays (z, u_pressure, u_temp, u_power, u_flow) so
bench_main's cascade_trace unit needs no filesystem access — this makes it
portable unchanged to the Corstone-300 FVP (Phase 3.5), which has none.

Same dataset as tests/golden/ekf_trace_seed42.json is recorded against
(phase1_physics, seed=config.SEED, n_steps=config.N_STEPS, k=1.0) — this is
the deterministic input; the golden trace is paci_core's recorded output for
that same input.

Usage: python tools/gen_bench_trace.py
"""
import os
import sys

_PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _PROJECT_ROOT)

import config  # noqa: E402
from phase1_physics.physics_model import PhysicsModel  # noqa: E402
from phase1_physics.synthetic_data import generate_full_dataset  # noqa: E402

_OUTPUT_PATH = os.path.join(_PROJECT_ROOT, "bench", "bench_trace.h")


def _c_float_array(name, values):
    body = ", ".join(f"{v!r}f" for v in values)
    return f"static const float {name}[{len(values)}] = {{{body}}};"


def main():
    physics = PhysicsModel()
    dataset = generate_full_dataset(physics, n_steps=config.N_STEPS, seed=config.SEED, k=1.0)

    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Generated by tools/gen_bench_trace.py -- DO NOT EDIT BY HAND.",
        "// Standard 2000-step/seed-42 input trace (k=1.0), same dataset",
        "// tests/golden/ekf_trace_seed42.json is paci_core's recorded output for.",
        "#ifndef BENCH_TRACE_H",
        "#define BENCH_TRACE_H",
        "",
        f"#define BENCH_TRACE_STEPS {config.N_STEPS}",
        "",
        _c_float_array("bench_trace_z", [float(v) for v in dataset["measured_etch_rate"]]),
        _c_float_array("bench_trace_pressure", [float(v) for v in dataset["params"]["pressure"]]),
        _c_float_array("bench_trace_temperature", [float(v) for v in dataset["params"]["temperature"]]),
        _c_float_array("bench_trace_power", [float(v) for v in dataset["params"]["rf_power"]]),
        _c_float_array("bench_trace_flow", [float(v) for v in dataset["params"]["gas_flow"]]),
        "",
        "#endif // BENCH_TRACE_H",
        "",
    ]

    os.makedirs(os.path.dirname(_OUTPUT_PATH), exist_ok=True)
    with open(_OUTPUT_PATH, "w", newline="\n", encoding="ascii") as f:
        f.write("\n".join(lines))
    print(f"Wrote {_OUTPUT_PATH}")


if __name__ == "__main__":
    main()
